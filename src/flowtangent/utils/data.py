class Dataset(torch.utils.data.Dataset):
    def __new__(cls, source=None, *args, **kwargs):
        if cls is not Dataset:
            return super().__new__(cls)

        if source is None:
            raise ValueError("ft.Dataset requires a source when instantiated directly.")

        if isinstance(source, (str, Path)):
            src_str = str(source).lower()

            if src_str.endswith(".zarr"):
                return ZarrDataset(source, *args, **kwargs)
            elif src_str.endswith((".h5", ".hdf5")):
                return HDF5Dataset(source, *args, **kwargs)
            elif src_str.endswith(".parquet"):
                return ParquetDataset(source, *args, **kwargs)
            elif src_str.endswith(".csv"):
                return CSVDataset(source, *args, **kwargs)
            elif src_str.endswith((".nc", ".nc4", ".netcdf")):
                return NetCDFDataset(source, *args, **kwargs)
            elif src_str.endswith(".mat"):
                return MATDataset(source, *args, **kwargs)
            else:
                raise ValueError(f"Unsupported data format extension: {source}")

        elif hasattr(source, "columns") and hasattr(source, "iloc"):
            return DataFrameDataset(source, *args, **kwargs)

        raise TypeError(f"Unsupported data source type: {type(source)}")

    def __getitem__(self, idx):
        raise NotImplementedError

    def __len__(self):
        raise NotImplementedError

