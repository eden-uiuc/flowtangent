# DataLoader
#-----------------------------------------------------------------------------------------------------------------------

class DataLoader(torch.utils.data.DataLoader):
    def __init__(self, dataset, batch_size=1, shuffle=False, num_workers=0, **kwargs):
        
        # If batching is enabled, use the collator to stack and convert
        if batch_size is not None and 'collate_fn' not in kwargs:
            kwargs['collate_fn'] = numpy_collate
            
        # If batching is disabled (None), use the converter to just convert
        elif batch_size is None and 'collate_fn' not in kwargs:
            kwargs['collate_fn'] = numpy_convert 
            
        kwargs['pin_memory'] = False 
        
        super().__init__(
            dataset=dataset,
            batch_size=batch_size,
            shuffle=shuffle,
            num_workers=num_workers,
            **kwargs
        )

