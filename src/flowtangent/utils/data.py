# Helper Functions
#-----------------------------------------------------------------------------------------------------------------------

def numpy_convert(elem):
    """Converts a single element (or nested elements) to NumPy. Replaces default_convert."""
    if isinstance(elem, torch.Tensor):
        return elem.detach().cpu().numpy()
    elif isinstance(elem, np.ndarray):
        return elem
    elif isinstance(elem, (tuple, list)):
        return type(elem)(numpy_convert(x) for x in elem)
    elif isinstance(elem, dict):
        return {k: numpy_convert(v) for k, v in elem.items()}
    else:
        return elem

def numpy_collate(batch):
    """Recursively converts to NumPy and stacks the batch. Replaces default_collate."""
    elem = batch[0]
    
    if isinstance(elem, torch.Tensor):
        # Catch any rogue PyTorch tensors generated by legacy datasets
        return np.stack([x.detach().cpu().numpy() for x in batch])
    elif isinstance(elem, np.ndarray):
        return np.stack(batch)
    elif isinstance(elem, (int, float)):
        return np.array(batch)
    elif isinstance(elem, (tuple, list)):
        transposed = zip(*batch)
        return type(elem)(numpy_collate(samples) for samples in transposed)
    elif isinstance(elem, dict):
        return {key: numpy_collate([d[key] for d in batch]) for key in elem}
    else:
        raise TypeError(f"numpy_collate cannot handle batch of type {type(elem)}")

